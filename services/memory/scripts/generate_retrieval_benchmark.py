"""Generate a JSON retrieval benchmark: queries + standard node summaries +
complete (full) query↔node cosine-similarity table.

Outputs one JSON file with five parts:
  1. ``meta``            — embedder/metric/sizes;
  2. ``queries``         — data-driven query series: one per distinct real
                           object-observation summary (scene path) plus every
                           real plan query (plan path) — nothing hand-written;
  3. ``scene_nodes``     — standard-format object-node summaries;
  4. ``plan_nodes``      — standard-format plan-node summaries;
  5. ``similarity``      — per query, the FULL scores against every scene node
                           and every plan node (not just top-k), sorted desc.

The scene summaries follow the design-doc "补充：双路径 embedding / 存储精简"
simplified schema (no embedding vector, no raw_log / 3D spatial / camera_params
/ depth·video refs); plan summaries keep query/description/counts. Vectors are
read raw from Milvus on-disk files (parquet + arrow WAL, no lock) and text from
the JSON snapshots, so it runs while the service holds the LOCK and needs no
MongoDB.

Usage:
    cd services/memory
    HF_ENDPOINT=https://hf-mirror.com rbnx-build/venv/bin/python \
        scripts/generate_retrieval_benchmark.py \
        [--milvus-dir ./memory/robonix_memory.db] \
        [--scene-json ./memory/graph_store.json] \
        [--plan-json ./memory/ptdl_store.json] \
        [--out ./memory/retrieval_benchmark.json]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import time
from datetime import datetime, timezone

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

MILVUS_COLLECTION = "memory_vectors"

# Natural Chinese questions (normal usage) that exercise retrieval, grounded in
# the real stored data. 100 queries are generated by applying natural templates
# to the real entities below — no invented objects/tasks.
#   scene → the object label present in ``objects_present`` of the target node;
#   plan  → a substring of the real stored plan ``query``.

SCENE_OBJECTS = [
    ("potted_plant", "绿植"),
    ("chair", "椅子"),
    ("table", "桌子"),
    ("lamp", "灯"),
    ("laptop", "笔记本电脑"),
    ("keyboard", "键盘"),
    ("monitor", "显示器"),
    ("cabinet", "柜子"),
    ("couch", "沙发"),
    ("trash_bin", "垃圾桶"),
    ("door", "门"),
    ("shelf", "置物架"),
]

SCENE_TEMPLATES = [
    "哪里有{}？",
    "{}在哪里？",
    "我之前在哪里看到过{}？",
    "我观察过{}吗？",
    "这个环境里有没有{}？",
]

# 动作类任务：短语 → 对应真实 plan query 子串（用于判定命中）
PLAN_ACTIONS = [
    ("去厨房拿一个水杯",         "去厨房拿一个水杯"),
    ("整理办公室西侧的书桌",     "整理办公室西侧的书桌"),
    ("检查门口是否有障碍物",     "检查门口是否有障碍物"),
    ("巡逻客厅并记录看到的物品", "巡逻客厅并记录看到的物品"),
    ("去厨房区域探索一圈",       "去厨房区域探索一圈"),
    ("探索办公室西侧的门",       "手动探索到办公室西侧实体门位置"),
]

PLAN_ACTION_TEMPLATES = [
    "{}",
    "怎么{}？",
    "我之前做过{}吗？",
    "帮我{}",
]

# 问答类任务：真实 plan query 子串 → 4 条自然问法
PLAN_QUESTIONS = [
    ("做过什么任务", [
        "我昨天做过什么任务？",
        "昨天我完成了哪些任务？",
        "我昨天都干了什么？",
        "回顾一下我昨天做过的任务",
    ]),
    ("场景记忆", [
        "我的场景记忆里现在有哪些物体？",
        "我现在记住了哪些物体？",
        "场景记忆里存了哪些物体？",
        "我的记忆里都有哪些物体？",
    ]),
    ("完成过哪些任务", [
        "我以前完成过哪些任务？",
        "我做过哪些任务？",
        "历史上我完成过什么任务？",
        "我有哪些已经完成的任务？",
    ]),
    ("现在能看到什么", [
        "我现在能看到什么？",
        "当前我看到了什么？",
        "我眼前有什么物体？",
        "现在视野里有什么？",
    ]),
]


def _build_queries() -> list:
    """Generate 100 natural Chinese queries from real entities + templates."""
    queries = []

    def add(path: str, text: str, expected: str) -> None:
        queries.append({"id": f"Q{len(queries) + 1:03d}",
                        "path": path, "text": text, "expected": expected})

    for label, name in SCENE_OBJECTS:
        for tpl in SCENE_TEMPLATES:
            add("scene", tpl.format(name), label)

    for phrase, expected in PLAN_ACTIONS:
        for tpl in PLAN_ACTION_TEMPLATES:
            add("plan", tpl.format(phrase), expected)

    for expected, variants in PLAN_QUESTIONS:
        for v in variants:
            add("plan", v, expected)

    return queries


def _read_arrow_ipc(fp: str):
    import pyarrow.ipc as ipc

    last = None
    for _ in range(3):
        try:
            with open(fp, "rb") as f:
                return ipc.open_stream(f.read()).read_all()
        except Exception as e:
            last = e
            time.sleep(0.05)
    raise last


def _read_raw_vectors(path: str) -> dict:
    """doc_id -> (kind, np.ndarray). Last ``_seq`` wins."""
    import pyarrow.parquet as pq

    col_dir = os.path.join(path, "collections", MILVUS_COLLECTION)
    manifest = {}
    mpath = os.path.join(col_dir, "manifest.json")
    if os.path.exists(mpath):
        with open(mpath, encoding="utf-8") as f:
            manifest = json.load(f)

    latest: dict = {}

    def note(seq: int, doc_id: str, row) -> None:
        cur = latest.get(doc_id)
        if cur is None or seq > cur[0]:
            latest[doc_id] = (seq, row)

    def apply_table(tbl, *, is_delete: bool) -> None:
        seqs = tbl.column("_seq").to_pylist()
        docs = tbl.column("doc_id").to_pylist()
        if is_delete:
            for s, d in zip(seqs, docs):
                note(int(s), str(d), None)
            return
        kinds = tbl.column("kind").to_pylist()
        vecs = tbl.column("vector").to_pylist()
        for s, d, k, v in zip(seqs, docs, kinds, vecs):
            note(int(s), str(d),
                 (k, np.asarray(v, dtype=np.float32).reshape(-1)))

    part = manifest.get("partitions", {}).get("_default", {})
    pdir = os.path.join(col_dir, "partitions", "_default")
    for rel in part.get("data_files", []):
        fp = os.path.join(pdir, rel)
        if os.path.exists(fp):
            apply_table(pq.read_table(fp), is_delete=False)
    for rel in part.get("delta_files", []):
        fp = os.path.join(pdir, rel)
        if os.path.exists(fp):
            apply_table(pq.read_table(fp), is_delete=True)

    wal_dir = os.path.join(col_dir, "wal")
    if os.path.isdir(wal_dir):
        for name in sorted(os.listdir(wal_dir)):
            if not name.endswith(".arrow"):
                continue
            is_delete = name.startswith("wal_delta_")
            if not (name.startswith("wal_data_") or is_delete):
                continue
            apply_table(_read_arrow_ipc(os.path.join(wal_dir, name)),
                        is_delete=is_delete)

    return {d: r for d, (_s, r) in latest.items() if r is not None}


def _load_embedder():
    from memory_service.storage.bge_embedder import BgeEmbedder
    from memory_service.storage.embedding_config import EmbeddingModelConfig

    return BgeEmbedder(EmbeddingModelConfig())


def _scene_summaries(scene_json: str) -> list:
    """Standard-format object-node summaries (simplified schema).

    Only observation/object nodes (``node_type != "place"``) are included —
    the grid-cell ``place`` rows are positional bookkeeping, not object
    memory, so they are left out of the object-node benchmark.
    """
    out = []
    if not os.path.exists(scene_json):
        return out
    with open(scene_json, encoding="utf-8") as f:
        nodes = json.load(f).get("nodes", [])
    for n in nodes:
        if n.get("node_type") == "place":
            continue
        tags = n.get("tags") or {}
        out.append({
            "node_id": n.get("node_id"),
            "node_type": n.get("node_type"),
            "timestamp": n.get("timestamp"),
            "summary_en": n.get("summary_en") or n.get("summary") or "",
            "summary_zh": n.get("summary_zh") or "",
            "objects_present": tags.get("objects_present") or [],
            "scene_type": tags.get("scene_type") or "",
            "region": tags.get("region") or "",
            "action_type": tags.get("action_type") or "",
            "success": tags.get("success"),
            "task_type": tags.get("task_type") or "",
            "intent": tags.get("intent") or "",
            "weight": n.get("weight"),
            "version": n.get("version"),
        })
    return out


def _plan_summaries(plan_json: str) -> list:
    """Standard-format plan-node summaries (simplified schema)."""
    out = []
    if not os.path.exists(plan_json):
        return out
    with open(plan_json, encoding="utf-8") as f:
        entries = json.load(f)
    for e in entries:
        q = (e.get("query") or "").strip()
        if not q:
            continue
        out.append({
            "doc_id": hashlib.sha1(q.encode("utf-8")).hexdigest(),
            "query": q,
            "description": e.get("description") or "",
            "timestamp_ns": e.get("timestamp_ns"),
            "plan_count": e.get("plan_count", 0),
            "canceled_count": e.get("canceled_count", 0),
        })
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate retrieval benchmark JSON.")
    ap.add_argument("--milvus-dir", default="./memory/robonix_memory.db")
    ap.add_argument("--scene-json", default="./memory/graph_store.json")
    ap.add_argument("--plan-json", default="./memory/ptdl_store.json")
    ap.add_argument("--out", default="./memory/retrieval_benchmark.json")
    args = ap.parse_args(argv)

    path = os.path.abspath(os.path.expanduser(args.milvus_dir))
    vectors = _read_raw_vectors(path)
    scene_sum = _scene_summaries(args.scene_json)
    plan_sum = _plan_summaries(args.plan_json)
    emb = _load_embedder()

    scene_ids = {str(s["node_id"]) for s in scene_sum}
    plan_ids = {s["doc_id"] for s in plan_sum}
    scene_vec: dict = {}
    plan_vec: dict = {}
    for doc_id, (kind, v) in vectors.items():
        if kind == "scene" and doc_id in scene_ids:
            scene_vec[doc_id] = v
        elif kind == "plan" and doc_id in plan_ids:
            plan_vec[doc_id] = v

    queries = _build_queries()

    similarity = []
    for q in queries:
        qv = np.asarray(emb.encode(q["text"]), dtype=np.float32)
        qv = qv / (np.linalg.norm(qv) + 1e-12)

        sc = {}
        for s in scene_sum:
            v = scene_vec.get(str(s["node_id"]))
            if v is None:
                continue
            sc[str(s["node_id"])] = round(
                float(np.dot(qv, v / (np.linalg.norm(v) + 1e-12))), 6)
        pl = {}
        for p in plan_sum:
            v = plan_vec.get(p["doc_id"])
            if v is None:
                continue
            pl[p["doc_id"]] = round(
                float(np.dot(qv, v / (np.linalg.norm(v) + 1e-12))), 6)

        similarity.append({
            "query_id": q["id"],
            "query": q["text"],
            "path": q["path"],
            "expected": q["expected"],
            "scene_scores": dict(sorted(sc.items(), key=lambda x: -x[1])),
            "plan_scores": dict(sorted(pl.items(), key=lambda x: -x[1])),
        })

    result = {
        "meta": {
            "embedder": "BGE-M3 (gpahal/bge-m3-onnx-int8)",
            "dim": 1024,
            "metric": "cosine",
            "scene_nodes": len(scene_sum),
            "plan_nodes": len(plan_sum),
            "queries": len(queries),
            "generated_at": datetime.now(timezone.utc).isoformat(),
        },
        "queries": queries,
        "scene_nodes": scene_sum,
        "plan_nodes": plan_sum,
        "similarity": similarity,
    }

    out = os.path.abspath(os.path.expanduser(args.out))
    with open(out, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(f"wrote {out}")
    print(f"scene_nodes={len(scene_sum)} plan_nodes={len(plan_sum)} "
          f"queries={len(queries)} similarity={len(similarity)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
